# Vilkårlige nøkler for advisory locks i PostgreSQL, slik at flere instanser ikke oppretter tabellene
# eller kjører helsesjekken samtidig
_POSTGRES_SCHEMA_LOCK_ID = 4_718_293_651
_POSTGRES_RUN_LOCK_ID = 4_718_293_652

# Et mål er aktivt hvis det var med i siste kjøring, dvs. at det fortsatt finnes i konfigurasjonen
_ACTIVE_FILTER = 'AND t.pk IN (SELECT target_pk FROM results WHERE run_id = (SELECT MAX(id) FROM runs)) '

# SUM(r.status = 'ok') fungerer bare i SQLite, så tellingene skrives med CASE
_STATUS_COUNTS = ', '.join(
    f"SUM(CASE WHEN r.status = '{status}' THEN 1 ELSE 0 END) AS {status}"
    for status in ('ok', 'slow', 'degraded', 'down')
)

_init_lock = threading.Lock()
_initialized = False
_pool_lock = threading.Lock()
_pool: ConnectionPool | None = None


class _Connection:
    # Spørringene skrives med SQLite sine ?-plassholdere og oversettes til %s for PostgreSQL
    def __init__(self, connection: Any, postgres: bool) -> None:
        self._connection = connection
        self._postgres = postgres

    def execute(self, query: str, params: Sequence[Any] = ()) -> Any:
        if self._postgres:
            query = query.replace('?', '%s')

        return self._connection.execute(query, params)


@contextmanager
def _connect() -> Iterator[_Connection]:
    if settings.DB_URL:
        with _get_pool(settings.DB_URL).connection() as connection:
            _ensure_schema(lambda: _create_postgres_schema(connection))
            yield _Connection(connection, postgres=True)

        return

    path = Path(settings.DB_PATH)
    path.parent.mkdir(parents=True, exist_ok=True)

    connection = sqlite3.connect(path, timeout=30)
    connection.row_factory = sqlite3.Row
    connection.execute('PRAGMA foreign_keys = ON')

    try:
        _ensure_schema(lambda: connection.executescript(_SQLITE_SCHEMA))

        with connection:
            yield _Connection(connection, postgres=False)
    finally:
        connection.close()


def _ensure_schema(create: Callable[[], Any]) -> None:
    global _initialized

    with _init_lock:
        if not _initialized:
            create()
            _initialized = True


def _get_pool(conninfo: str) -> ConnectionPool:
    global _pool

    with _pool_lock:
        if _pool is None:
            _pool = ConnectionPool(
                conninfo,
                min_size=1,
                max_size=settings.DB_POOL_SIZE,
                kwargs={'row_factory': dict_row},
                configure=_configure_postgres_connection,
                name='healthcheck',
                open=True
            )

        return _pool


def _configure_postgres_connection(connection: Connection) -> None:
    connection.execute(sql.SQL('SET search_path TO {}').format(sql.Identifier(settings.DB_SCHEMA)))
    connection.commit()


def _create_postgres_schema(connection: Connection) -> None:
    # CREATE ... IF NOT EXISTS krever CREATE-rettighet selv om objektet finnes, så det sjekkes først.
    # Da holder det med lese- og skrivetilgang når skjemaet og tabellene er opprettet på forhånd.
    if _postgres_tables_exist(connection):
        return

    connection.execute('SELECT pg_advisory_xact_lock(%s)', (_POSTGRES_SCHEMA_LOCK_ID,))

    if connection.execute('SELECT 1 FROM pg_namespace WHERE nspname = %s', (settings.DB_SCHEMA,)).fetchone() is None:
        connection.execute(sql.SQL('CREATE SCHEMA {}').format(sql.Identifier(settings.DB_SCHEMA)))

    connection.execute(_POSTGRES_SCHEMA)  # type: ignore[arg-type]
    connection.commit()


def _postgres_tables_exist(connection: Connection) -> bool:
    row = connection.execute(
        'SELECT COUNT(*) AS count FROM pg_tables WHERE schemaname = %s AND tablename IN (%s, %s, %s)',
        (settings.DB_SCHEMA, 'runs', 'targets', 'results')
    ).fetchone()
    connection.commit()

    return row is not None and row['count'] == 3  # type: ignore[call-overload]


def acquire_run_lock() -> Callable[[], None] | None:
    # Returnerer en funksjon som slipper låsen, eller None hvis en annen instans kjører helsesjekken.
    # SQLite brukes bare av én prosess, så der holder låsen i runner.py.
    if not settings.DB_URL:
        return lambda: None

    pool = _get_pool(settings.DB_URL)
    connection = pool.getconn()

    try:
        # Låsen gjelder for sesjonen og holdes på denne tilkoblingen til den slippes eller tilkoblingen dør
        row = connection.execute(
            'SELECT pg_try_advisory_lock(%s) AS acquired', (_POSTGRES_RUN_LOCK_ID,)).fetchone()
        connection.commit()
        acquired = row is not None and row['acquired']  # type: ignore[call-overload]
    except Exception:
        pool.putconn(connection)
        raise

    if not acquired:
        pool.putconn(connection)
        return None

    def release() -> None:
        try:
            connection.execute('SELECT pg_advisory_unlock(%s)', (_POSTGRES_RUN_LOCK_ID,))
            connection.commit()
        except Exception:
            # Har tilkoblingen falt ut, er låsen allerede sluppet
            _logger.warning('Could not release healthcheck run lock', exc_info=True)
        finally:
            pool.putconn(connection)

    return release


def close() -> None:
    global _pool

    with _pool_lock:
        if _pool is not None:
            _pool.close()
            _pool = None


def save_run(summary: RunSummary, trigger: str) -> int:
    started_at = _to_epoch(summary.started_at)

    with _connect() as connection:
        run_id = connection.execute(
            'INSERT INTO runs (started_at, finished_at, trigger, config_ref, config_commit, config_source) '
            'VALUES (?, ?, ?, ?, ?, ?) RETURNING id',
            (started_at, _to_epoch(summary.finished_at), trigger,
             summary.config_ref, summary.config_commit, summary.config_source)
        ).fetchone()['id']

        for result in summary.results:
            target = result.target
            target_pk = connection.execute(
                'INSERT INTO targets (id, kind, name, service_type, url, meta, first_seen, last_seen) '
                'VALUES (?, ?, ?, ?, ?, ?, ?, ?) '
                'ON CONFLICT(id) DO UPDATE SET kind = excluded.kind, name = excluded.name, '
                'service_type = excluded.service_type, url = excluded.url, meta = excluded.meta, '
                'last_seen = excluded.last_seen '
                'RETURNING pk',
                (target.id, target.kind, target.name, target.service_type, target.url,
                 _dumps(target.meta), started_at, started_at)
            ).fetchone()['pk']

            connection.execute(
                'INSERT INTO results (run_id, target_pk, checked_at, status, http_status, response_ms, message, details) '
                'VALUES (?, ?, ?, ?, ?, ?, ?, ?)',
                (run_id, target_pk, _to_epoch(result.checked_at), result.status.value,
                 result.http_status, result.response_ms, result.message,
                 _dumps(result.details) if result.details else None)
            )

        return run_id


def delete_old_results() -> None:
    now = datetime.now(timezone.utc)
    cutoff = _to_epoch(now - timedelta(days=settings.RETENTION_DAYS))
    details_cutoff = _to_epoch(now - timedelta(days=settings.DETAILS_RETENTION_DAYS))

    with _connect() as connection:
        connection.execute('DELETE FROM runs WHERE started_at < ?', (cutoff,))
        connection.execute('DELETE FROM targets WHERE pk NOT IN (SELECT target_pk FROM results)')
        connection.execute(
            'UPDATE results SET details = NULL WHERE checked_at < ? AND details IS NOT NULL', (details_cutoff,))


def get_latest_run() -> Dict[str, Any] | None:
    with _connect() as connection:
        row = connection.execute('SELECT * FROM runs ORDER BY id DESC LIMIT 1').fetchone()

        return _run_to_dict(row) if row else None


def get_latest_run_id() -> int | None:
    with _connect() as connection:
        return connection.execute('SELECT MAX(id) AS id FROM runs').fetchone()['id']


def get_latest_results(run_id: int) -> List[Dict[str, Any]]:
    with _connect() as connection:
        rows = connection.execute(
            'SELECT t.id AS target_id, t.kind, t.name, t.service_type, t.url, t.meta, '
            'r.checked_at, r.status, r.http_status, r.response_ms, r.message, r.details '
            'FROM results r JOIN targets t ON t.pk = r.target_pk '
            'WHERE r.run_id = ? ORDER BY t.kind, t.name',
            (run_id,)
        ).fetchall()

        return [_result_to_dict(row) for row in rows]


def get_target(target_id: str) -> Dict[str, Any] | None:
    with _connect() as connection:
        row = connection.execute('SELECT * FROM targets WHERE id = ?', (target_id,)).fetchone()

        if row is None:
            return None

        return {
            'id': row['id'],
            'kind': row['kind'],
            'name': row['name'],
            'service_type': row['service_type'],
            'url': row['url'],
            'meta': json.loads(row['meta']),
            'first_seen': _from_epoch(row['first_seen']),
            'last_seen': _from_epoch(row['last_seen'])
        }


def get_target_history(target_id: str, since: datetime) -> List[Dict[str, Any]]:
    with _connect() as connection:
        rows = connection.execute(
            'SELECT r.checked_at, r.status, r.http_status, r.response_ms, r.message '
            'FROM results r JOIN targets t ON t.pk = r.target_pk '
            'WHERE t.id = ? AND r.checked_at >= ? ORDER BY r.checked_at',
            (target_id, _to_epoch(since))
        ).fetchall()

        return [{
            'checked_at': _from_epoch(row['checked_at']),
            'status': row['status'],
            'http_status': row['http_status'],
            'response_ms': row['response_ms'],
            'message': row['message']
        } for row in rows]


def get_status_counts(since: datetime, include_inactive: bool = False) -> List[Row]:
    active_filter = '' if include_inactive else _ACTIVE_FILTER

    with _connect() as connection:
        return connection.execute(
            f'SELECT t.id AS target_id, COUNT(*) AS checks, {_STATUS_COUNTS} '
            'FROM results r JOIN targets t ON t.pk = r.target_pk '
            f'WHERE r.checked_at >= ? {active_filter}GROUP BY t.id ORDER BY t.id',
            (_to_epoch(since),)
        ).fetchall()


def get_response_times(since: datetime, include_inactive: bool = False) -> List[Row]:
    active_filter = '' if include_inactive else _ACTIVE_FILTER

    with _connect() as connection:
        return connection.execute(
            'SELECT t.id AS target_id, r.response_ms '
            'FROM results r JOIN targets t ON t.pk = r.target_pk '
            "WHERE r.checked_at >= ? AND r.response_ms IS NOT NULL AND r.status != 'down' "
            f'{active_filter}',
            (_to_epoch(since),)
        ).fetchall()


def get_hourly_counts(since: datetime, target_id: str | None = None, include_inactive: bool = False) -> List[Row]:
    # Et mål det spørres eksplisitt etter, returneres også om det er inaktivt
    target_filter = 'AND t.id = ? ' if target_id else ('' if include_inactive else _ACTIVE_FILTER)
    params: List[Any] = [_to_epoch(since)] + ([target_id] if target_id else [])

    with _connect() as connection:
        return connection.execute(
            f'SELECT t.id AS target_id, r.checked_at / 3600 AS hour, COUNT(*) AS checks, {_STATUS_COUNTS}, '
            'CAST(AVG(r.response_ms) AS DOUBLE PRECISION) AS avg_ms '
            'FROM results r JOIN targets t ON t.pk = r.target_pk '
            f'WHERE r.checked_at >= ? {target_filter}'
            'GROUP BY t.id, hour ORDER BY hour',
            params
        ).fetchall()


def get_status_sequence(since: datetime, kind: str | None = None, include_inactive: bool = False) -> List[Row]:
    kind_filter = 'AND t.kind = ? ' if kind else ''
    active_filter = '' if include_inactive else _ACTIVE_FILTER
    params: List[Any] = [_to_epoch(since)] + ([kind] if kind else [])

    with _connect() as connection:
        return connection.execute(
            'SELECT t.id AS target_id, t.name, t.kind, r.checked_at, r.status, r.http_status, r.message '
            'FROM results r JOIN targets t ON t.pk = r.target_pk '
            f'WHERE r.checked_at >= ? {kind_filter}{active_filter}ORDER BY t.id, r.checked_at',
            params
        ).fetchall()


def _run_to_dict(row: Row) -> Dict[str, Any]:
    return {
        'id': row['id'],
        'started_at': _from_epoch(row['started_at']),
        'finished_at': _from_epoch(row['finished_at']),
        'trigger': row['trigger'],
        'config_ref': row['config_ref'],
        'config_commit': row['config_commit'],
        'config_source': row['config_source']
    }


def _result_to_dict(row: Row) -> Dict[str, Any]:
    return {
        'target': {
            'id': row['target_id'],
            'kind': row['kind'],
            'name': row['name'],
            'service_type': row['service_type'],
            'url': row['url'],
            'meta': json.loads(row['meta'])
        },
        'checked_at': _from_epoch(row['checked_at']),
        'status': row['status'],
        'http_status': row['http_status'],
        'response_ms': row['response_ms'],
        'message': row['message'],
        'details': json.loads(row['details']) if row['details'] else {}
    }


def _dumps(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, default=str)


def _to_epoch(value: datetime) -> int:
    return int(value.timestamp())


def _from_epoch(value: int) -> str:
    return datetime.fromtimestamp(value, tz=timezone.utc).isoformat()


